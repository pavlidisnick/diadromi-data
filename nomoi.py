PREFIXES = ('Περιφερειακή Ενότητα ', 'Μητροπολιτική Ενότητα ')


def unit_to_nomos(name):
    """The bulletin name for an OpenStreetMap regional unit's Greek name, or None if it isn't one we know."""
    for p in PREFIXES:
        if name.startswith(p):
            name = name[len(p):]
    return UNITS.get(name.strip())


